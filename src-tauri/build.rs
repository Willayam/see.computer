fn main() {
    cc::Build::new()
        .file("native/menu.m")
        .flag("-fobjc-arc")
        .compile("seemenu");
    println!("cargo:rustc-link-lib=framework=AppKit");
    println!("cargo:rerun-if-changed=native/menu.m");
    cc::Build::new()
        .file("native/fix.m")
        .flag("-fobjc-arc")
        .compile("seefix");
    println!("cargo:rerun-if-changed=native/fix.m");
    cc::Build::new()
        .file("native/frame.m")
        .flag("-fobjc-arc")
        .compile("scframe");
    println!("cargo:rustc-link-lib=framework=AVFoundation");
    println!("cargo:rustc-link-lib=framework=CoreMedia");
    println!("cargo:rustc-link-lib=framework=CoreGraphics");
    println!("cargo:rustc-link-lib=framework=ImageIO");
    println!("cargo:rustc-link-lib=framework=Foundation");
    println!("cargo:rerun-if-changed=native/frame.m");
    cc::Build::new()
        .file("native/recording.m")
        .flag("-fobjc-arc")
        .flag("-mmacosx-version-min=14.0")
        .compile("screcording");
    println!("cargo:rustc-link-lib=framework=ScreenCaptureKit");
    println!("cargo:rustc-link-lib=framework=VideoToolbox");
    println!("cargo:rustc-link-lib=framework=CoreVideo");
    println!("cargo:rustc-link-lib=framework=AudioToolbox");
    println!("cargo:rustc-link-lib=framework=UniformTypeIdentifiers");
    println!("cargo:rustc-link-arg=-mmacosx-version-min=14.0");
    println!("cargo:rerun-if-changed=native/recording.m");
    cc::Build::new()
        .file("native/permissions.m")
        .flag("-fobjc-arc")
        .flag("-mmacosx-version-min=14.0")
        .compile("seepermissions");
    println!("cargo:rerun-if-changed=native/permissions.m");
    cc::Build::new()
        .file("native/tap.m")
        .flag("-fobjc-arc")
        .flag("-mmacosx-version-min=14.0")
        .compile("seetap");
    println!("cargo:rustc-link-lib=framework=CoreAudio");
    println!("cargo:rerun-if-changed=native/tap.m");
    // Only the windows a capability names may call these, so the pill keeps
    // no invoke surface at all.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "library_items",
            "library_copy",
            "library_reveal",
            "dictionary_load",
            "dictionary_stamp",
            "dictionary_edit",
            "dictionary_reveal",
        ]),
    ))
    .expect("failed to run tauri-build");
}
